-- data at login.
--
-- How palette colors map to roles, so markers stay apart and text stays read:
--   background  the palette's darkest surface (crust, bg_dim, bg0_h, ...)
--   rings       a quiet frame color (lavender, comment, gray)
--   accent      the palette's signature color (player, titles, buttons)
--   heading     the main text color, the brightest neutral
--   rare        blue or cyan       boss      red
--   treasure    yellow or gold     event     purple, magenta or pink
